def get(name: str) -> DatasetEntry:
    if name not in REGISTRY:
        raise KeyError(f"Unknown dataset '{name}'. Known: {sorted(REGISTRY)}")
    return REGISTRY[name]


def for_task(task: Task) -> list[DatasetEntry]:
    return [entry for entry in REGISTRY.values() if task in entry.tasks]


def downloadable() -> list[DatasetEntry]:
    """Datasets whose licence status permits acquisition.

    PENDING entries are excluded by design: the Phase 3 brief forbids
    downloading anything whose licensing is unclear.
    """
    return [
        entry
        for entry in REGISTRY.values()
        if entry.verification is not VerificationStatus.PENDING and entry.relative_path
    ]


def manifest() -> dict:
    """Serializable snapshot. Safe to commit — contains no data, no secrets."""
    return {
        "generated_by": "ml/data/registry.py",
        "datasets": {
            name: {
                **asdict(entry),
                "verification": entry.verification.value,
                "download": entry.download.value,
                "tasks": [t.value for t in entry.tasks],
            }
            for name, entry in REGISTRY.items()
        },
    }


def write_manifest(path: Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(manifest(), indent=2), encoding="utf-8")
    return path
