"""
S40 dataset registry.

Single source of truth for what each dataset is, where it legally came
from, whether we are allowed to use it, and whether it is present locally.

Verification status recorded here reflects what was actually checked from
authoritative sources on 2026-08-15 — see docs/DATA_STRATEGY.md for the
evidence trail. Nothing here is aspirational: a dataset that could not be
verified is marked PENDING and must not be downloaded (Phase 3 brief).

Local paths are resolved from the S40_DATA_DIR environment variable and
never hardcoded to a personal absolute path. Nothing in this module
downloads anything.
"""

from __future__ import annotations

import json
import os
from dataclasses import asdict, dataclass
from enum import Enum
from pathlib import Path

#: Default root for locally-acquired datasets, relative to the repo.
#: Overridable via S40_DATA_DIR. The directory is git-ignored.
DEFAULT_DATA_DIR = Path(__file__).resolve().parents[2] / "ml" / "data" / "raw"


class VerificationStatus(str, Enum):
    #: Licence and provenance confirmed from an authoritative source.
    VERIFIED = "VERIFIED"
    #: Provenance confirmed, licence text could not be read programmatically.
    PARTIALLY_VERIFIED = "PARTIALLY_VERIFIED"
    #: Not yet confirmed. MUST NOT be downloaded until it is.
    PENDING = "PENDING"


class DownloadStatus(str, Enum):
    NOT_DOWNLOADED = "NOT_DOWNLOADED"
    PRESENT = "PRESENT"


class Task(str, Enum):
    TRANSACTION_FRAUD = "TRANSACTION_FRAUD"
    ANOMALY_VALIDATION = "ANOMALY_VALIDATION"
    VOICE_SOCIAL_ENGINEERING = "VOICE_SOCIAL_ENGINEERING"
    SCENARIO_TESTING = "SCENARIO_TESTING"


@dataclass(frozen=True)
class DatasetEntry:
    name: str
    description: str
    #: Authoritative origin, not a mirror.
    source_url: str
    provenance: str
    licence: str
    licence_notes: str
    verification: VerificationStatus
    download: DownloadStatus
    #: Path fragment beneath the data dir. Never absolute.
    relative_path: str
    adapter: str
    target_field: str | None
    tasks: tuple[Task, ...]
    limitations: str
    #: True only if the source explicitly supports calling it real-world data.
    is_real_world_data: bool

    def local_path(self, data_dir: Path | None = None) -> Path:
        root = Path(data_dir) if data_dir else data_dir_from_env()
        return root / self.relative_path

    def is_present(self, data_dir: Path | None = None) -> bool:
        return self.local_path(data_dir).exists()


def data_dir_from_env() -> Path:
    configured = os.environ.get("S40_DATA_DIR")
    return Path(configured) if configured else DEFAULT_DATA_DIR


